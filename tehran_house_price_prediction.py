class RandomizedSearchCVProgressXGB(RandomizedSearchCV):
    """RandomizedSearchCV with progress bar for XGBoost"""

    def _run_search(self, evaluate_candidates):
        params_iter = list(ParameterSampler(self.param_distributions, self.n_iter, random_state=self.random_state))
        total = len(params_iter)
        with Progress(SpinnerColumn(), BarColumn(), TextColumn("{task.completed}/{task.total} trials"), TimeElapsedColumn(), console=console) as prog:
            task = prog.add_task("[green]XGB Hyperparameter Tuning", total=total)
            for params in params_iter:
                evaluate_candidates([params])
                prog.update(task, advance=1)

xgb_base = XGBRegressor(objective="reg:squarederror", random_state=42, n_jobs=-1)

xgb_search = RandomizedSearchCVProgressXGB(
    estimator=xgb_base,
    param_distributions=xgb_param_dist,
    n_iter=60,
    cv=5,
    n_jobs=-1,
    scoring="neg_mean_absolute_error",
    random_state=42,
)

