# %% 🚀 Advanced Model with Hyperparameter Tuning, LIME & SHAP
# This section builds on the cleaned data `df`, using the same feature set defined above.
# It performs hyperparameter tuning on a RandomForestRegressor, evaluates the tuned model,
# and generates LIME and SHAP explanations, saving everything into a time-stamped run folder.

import os
from datetime import datetime
from scipy.stats import randint
import shap
import lime.lime_tabular
import warnings
warnings.filterwarnings("ignore")

from rich.progress import Progress, SpinnerColumn, BarColumn, TextColumn, TimeElapsedColumn
from rich.table import Table
from rich.console import Console
console = Console()

# 1️⃣ Results directory structure (RandomForest) -------------------------------------------
base_results_dir = os.path.join(os.path.dirname(__file__), "results")
# Timestamp used for both model runs to group outputs from the same script execution
timestamp = datetime.now().strftime("%Y%m%d_%H%M")

# ---------------- RandomForest run-specific directories ----------------
rf_parent_dir = os.path.join(base_results_dir, "RandomForest")
rf_run_dir = os.path.join(rf_parent_dir, f"run_{timestamp}")

lime_dir = os.path.join(rf_run_dir, "lime")
shap_dir = os.path.join(rf_run_dir, "shap")
results_dir = os.path.join(rf_run_dir, "results")

for _d in (base_results_dir, rf_parent_dir, rf_run_dir, lime_dir, shap_dir, results_dir):
    os.makedirs(_d, exist_ok=True)

# Progress notification
console.print("\n⏳ Starting RandomForest hyperparameter tuning...")

# 2️⃣ Hyperparameter tuning -----------------------------------------------------------------
param_dist = {
    "n_estimators": randint(100, 1000),
    "max_depth": randint(3, 30),
    "min_samples_split": randint(2, 10),
    "min_samples_leaf": randint(1, 10),
    "max_features": ["sqrt", "log2", None],
}

# -------------------------------------------------------------------------
# RandomizedSearchCV with lightweight progress bar (outer n_iter only)
# -------------------------------------------------------------------------
class RandomizedSearchCVProgress(RandomizedSearchCV):
    """RandomizedSearchCV subclass that shows a progress bar per candidate."""

    def _run_search(self, evaluate_candidates):
        param_iter = list(ParameterSampler(self.param_distributions, self.n_iter, random_state=self.random_state))
        total = len(param_iter)
        with Progress(SpinnerColumn(), BarColumn(), TextColumn("{task.completed}/{task.total} trials"), TimeElapsedColumn(), console=console) as prog:
            task = prog.add_task("[green]Hyperparameter Tuning", total=total)
            for params in param_iter:
                evaluate_candidates([params])
                prog.update(task, advance=1)

# instantiate search
rf_base = RandomForestRegressor(random_state=42)
search = RandomizedSearchCVProgress(
    estimator=rf_base,
    param_distributions=param_dist,
    n_iter=100,
    cv=5,
    n_jobs=-1,
    scoring="neg_mean_absolute_error",
    random_state=42,
)

search.fit(X_train, y_train)
best_model = search.best_estimator_
best_params = search.best_params_

# 3️⃣ Evaluation ----------------------------------------------------------------------------
y_pred_tuned = best_model.predict(X_test)
mae_tuned = mean_absolute_error(y_test, y_pred_tuned)
rmse_tuned = np.sqrt(mean_squared_error(y_test, y_pred_tuned))
r2_tuned = r2_score(y_test, y_pred_tuned)

# Save metrics & best params
import csv
metrics_path = os.path.join(results_dir, "metrics_and_best_params.csv")
with open(metrics_path, "w", newline="") as _csv:
    writer = csv.writer(_csv)
    writer.writerow(["MAE", "RMSE", "R2", "BestParams"])
    writer.writerow([mae_tuned, rmse_tuned, r2_tuned, best_params])

# Save predictions with error columns
pred_df = pd.DataFrame({
    "Actual": y_test.values,
    "Predicted": y_pred_tuned,
})
pred_df["Absolute_Error"] = (pred_df["Actual"] - pred_df["Predicted"]).abs()
pred_df["Relative_Error"] = pred_df["Absolute_Error"] / pred_df["Actual"].replace(0, np.nan)

pred_df.to_csv(os.path.join(results_dir, "predictions.csv"), index=False)

# 4️⃣ SHAP Global Explanations --------------------------------------------------------------
with Progress(SpinnerColumn(), BarColumn(), TextColumn("[progress.description]{task.description}"), TimeElapsedColumn()) as progress:
    shap_task = progress.add_task("[cyan]Generating SHAP plots...", total=1)
    explainer = shap.TreeExplainer(best_model)
    shap_values = explainer.shap_values(X_train)
    progress.update(shap_task, advance=1)

# Summary plot
plt.figure()
shap.summary_plot(shap_values, X_train, show=False)
plt.savefig(os.path.join(shap_dir, "summary_plot.png"), bbox_inches="tight")
plt.close()

# Bar plot
plt.figure()
shap.summary_plot(shap_values, X_train, plot_type="bar", show=False)
plt.savefig(os.path.join(shap_dir, "bar_plot.png"), bbox_inches="tight")
plt.close()

# Dependence plot for most influential feature
_top_feature_idx = np.abs(shap_values).mean(axis=0).argmax()
_top_feature = X_train.columns[_top_feature_idx]
plt.figure()
shap.dependence_plot(_top_feature, shap_values, X_train, show=False)
plt.savefig(os.path.join(shap_dir, f"dependence_{_top_feature}.png"), bbox_inches="tight")
plt.close()

# 5️⃣ LIME Local Explanations ---------------------------------------------------------------
with Progress(SpinnerColumn(), BarColumn(), TextColumn("[progress.description]{task.description}"), TimeElapsedColumn()) as progress:
    lime_task = progress.add_task("[magenta]Generating LIME explanations...", total=1)
    lime_explainer = lime.lime_tabular.LimeTabularExplainer(
        training_data=X_train.values,
        feature_names=X_train.columns.tolist(),
        mode="regression",
    )
    progress.update(lime_task, advance=1)

sample_indices = np.random.choice(X_test.index, size=min(5, len(X_test)), replace=False)
for i, idx in enumerate(sample_indices, start=1):
    lime_exp = lime_explainer.explain_instance(
        data_row=X_test.loc[idx].values,
        predict_fn=best_model.predict,
    )
    fig = lime_exp.as_pyplot_figure()
    fig.savefig(os.path.join(lime_dir, f"lime_explanation_{i}.png"), bbox_inches="tight")
    plt.close(fig)

# 6️⃣ Console summary table ---------------------------------------------------------------
console.print(f"✅ RandomForest run completed. All outputs saved to: [bold yellow]{rf_run_dir}[/]")

